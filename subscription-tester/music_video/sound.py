"""Sound design for the cut: the music drops away before the reveal line, a quiet machine hum, room on the voice.

All of it is built from the song (or its stems), the spoken take and FFmpeg's own generators. Nothing is generated by a
provider, and no generated singing is ever used. The settings live on the project as `sound`; `filters` turns them into
FFmpeg filter fragments that render.build_command splices into its audio graph.
"""
import copy

DEFAULT = dict(
    reveal=dict(enabled=True, shot_id=None, lead_s=.6, fall_s=.25, depth_db=18.0, release_s=1.2),
    hum=dict(enabled=False, level_db=-34.0, freq=55.0, swell_db=10.0),
    voice=dict(room=.25),
)
LIMITS = {
    ('reveal', 'lead_s'): (0, 4), ('reveal', 'fall_s'): (.02, 2), ('reveal', 'depth_db'): (0, 60), ('reveal', 'release_s'): (.05, 6),
    ('hum', 'level_db'): (-60, -12), ('hum', 'freq'): (30, 200), ('hum', 'swell_db'): (0, 24),
    ('voice', 'room'): (0, 1),
}


class SoundError(ValueError):
    pass


def settings(current=None, changes=None):
    """Merge changes into the settings, validating every value."""
    out = copy.deepcopy(DEFAULT)
    for src in (current or {}, changes or {}):
        if not isinstance(src, dict) or set(src) - set(DEFAULT):
            raise SoundError('sound has reveal, hum and voice.')
        for group, values in src.items():
            if not isinstance(values, dict) or set(values) - set(DEFAULT[group]):
                raise SoundError(f'sound.{group} fields: ' + ', '.join(DEFAULT[group]))
            for key, v in values.items():
                if key == 'enabled':
                    if type(v) is not bool:
                        raise SoundError(f'sound.{group}.enabled is true or false.')
                elif key == 'shot_id':
                    if v is not None and not isinstance(v, str):
                        raise SoundError('sound.reveal.shot_id is a shot id or null (the last spoken shot).')
                else:
                    low, high = LIMITS[(group, key)]
                    if type(v) not in (int, float) or not low <= v <= high:
                        raise SoundError(f'sound.{group}.{key} must be from {low} to {high}.')
                    v = float(v)
                out[group][key] = v
    return out


def reveal_window(cfg, placements):
    """(dip_start, speech_start, speech_end) for the reveal shot, or None."""
    if not cfg['reveal']['enabled']:
        return None
    spoken = [p for p in placements if p.get('speech') and p.get('speech_start') is not None]
    if cfg['reveal'].get('shot_id'):
        spoken = [p for p in spoken if p.get('shot') == cfg['reveal']['shot_id']]
    if not spoken:
        return None
    p = max(spoken, key=lambda x: x['start'])
    return max(0.0, p['speech_start'] - cfg['reveal']['lead_s']), p['speech_start'], p['speech_end']


def dip_expression(a, e, fall, release, depth_db):
    """Music gain: 1 until a, falls to the dip over `fall`, holds to e, recovers over `release`."""
    g = 10 ** (-depth_db / 20)
    return (f"if(lt(t,{a:.3f}),1,if(lt(t,{a + fall:.3f}),1-{1 - g:.5f}*(t-{a:.3f})/{fall:.3f},"
            f"if(lt(t,{e:.3f}),{g:.5f},if(lt(t,{e + release:.3f}),{g:.5f}+{1 - g:.5f}*(t-{e:.3f})/{release:.3f},1))))")


def filters(cfg, placements, total):
    """FFmpeg fragments: {music: ',volume=...' or '', voice: ',aecho=...' or '', hum: 'aevalsrc=...[hum]' or None, plan}."""
    out = dict(music='', voice='', hum=None, plan={})
    win = reveal_window(cfg, placements)
    if win and cfg['reveal']['depth_db'] > 0:
        a, s, e = win
        r = cfg['reveal']
        out['music'] = f",volume='{dip_expression(a, e, r['fall_s'], r['release_s'], r['depth_db'])}':eval=frame"
        out['plan']['reveal'] = dict(dip_start=round(a, 3), speech_start=round(s, 3), speech_end=round(e, 3), depth_db=r['depth_db'])
    room = cfg['voice']['room']
    if room > 0:
        out['voice'] = f",aecho=0.85:0.8:{int(23 + 30 * room)}|{int(47 + 60 * room)}:{.35 * room:.3f}|{.22 * room:.3f}"
        out['plan']['voice_room'] = room
    h = cfg['hum']
    if h['enabled']:
        base = 10 ** (h['level_db'] / 20)
        peak = base * 10 ** (h['swell_db'] / 20)
        if win:
            a, s, e = win
            env = (f"if(lt(t,{a:.3f}),{base:.6f},if(lt(t,{s:.3f}),{base:.6f}+{peak - base:.6f}*(t-{a:.3f})/{max(.05, s - a):.3f},"
                   f"if(lt(t,{e + 1:.3f}),{peak:.6f},{peak:.6f}*exp(-(t-{e + 1:.3f})/1.5))))")
        else:
            env = f'{base:.6f}'
        f = h['freq']
        out['hum'] = (f"aevalsrc='({env})*(0.7*sin(2*PI*{f:.2f}*t)+0.3*sin(2*PI*{2 * f:.2f}*t))*(0.8+0.2*sin(2*PI*0.25*t))'"
                      f":s=44100:d={total:.3f},lowpass=f=400[hum]")
        out['plan']['hum'] = dict(level_db=h['level_db'], swell_db=h['swell_db'] if win else 0, freq=f)
    return out
