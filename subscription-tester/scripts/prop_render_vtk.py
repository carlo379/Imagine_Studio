"""VTK worker for prop_models: render one posed mesh to a transparent PNG.

Usage: python -I prop_render_vtk.py JOB.json   (written by prop_models.run_engine)
Camera at the origin looking down -Z, +Y up, vertical field of view from the job.
"""
import json
import sys

import vtk

job = json.loads(open(sys.argv[1]).read())
reader = vtk.vtkSTLReader() if job['format'] == 'stl' else vtk.vtkOBJReader()
reader.SetFileName(job['mesh'])
transform = vtk.vtkTransform()
transform.SetMatrix([v for row in job['matrix'] for v in row])
placed = vtk.vtkTransformPolyDataFilter()
placed.SetInputConnection(reader.GetOutputPort())
placed.SetTransform(transform)
normals = vtk.vtkPolyDataNormals()
normals.SetInputConnection(placed.GetOutputPort())
normals.SetFeatureAngle(35)
normals.SplittingOn()
normals.ConsistencyOn()
normals.AutoOrientNormalsOn()
mapper = vtk.vtkPolyDataMapper()
mapper.SetInputConnection(normals.GetOutputPort())
actor = vtk.vtkActor()
actor.SetMapper(mapper)
prop = actor.GetProperty()
prop.SetColor(*job['color'])
prop.SetDiffuse(0.85)
prop.SetAmbient(0.18)
prop.SetSpecular(0.12)
prop.SetSpecularPower(18)

ren = vtk.vtkRenderer()
ren.SetBackground(0, 0, 0)
ren.SetBackgroundAlpha(0.0)
ren.AddActor(actor)
ren.RemoveAllLights()
ren.AutomaticLightCreationOff()
for position, intensity in (((0.6, 0.8, 1.0), 0.75), ((-0.9, 0.2, 0.6), 0.35), ((0.0, -0.6, 1.0), 0.20)):
    light = vtk.vtkLight()
    light.SetLightTypeToCameraLight()
    light.SetPosition(*position)
    light.SetFocalPoint(0, 0, 0)
    light.SetIntensity(intensity)
    ren.AddLight(light)

cam = ren.GetActiveCamera()
cam.SetPosition(0, 0, 0)
cam.SetFocalPoint(0, 0, -1)
cam.SetViewUp(0, 1, 0)
cam.SetViewAngle(job['vfov_deg'])
ren.ResetCameraClippingRange()
near, far = cam.GetClippingRange()
cam.SetClippingRange(max(1e-3, near * 0.5), far * 2)

win = vtk.vtkRenderWindow()
win.SetOffScreenRendering(1)
win.SetAlphaBitPlanes(1)
win.SetMultiSamples(0)
win.AddRenderer(ren)
win.SetSize(job['width'], job['height'])
ren.SetUseFXAA(True)
win.Render()
grab = vtk.vtkWindowToImageFilter()
grab.SetInput(win)
grab.SetInputBufferTypeToRGBA()
grab.ReadFrontBufferOff()
grab.Update()
writer = vtk.vtkPNGWriter()
writer.SetFileName(job['output'])
writer.SetInputConnection(grab.GetOutputPort())
writer.Write()
