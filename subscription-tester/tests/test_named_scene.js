const assert=require('node:assert/strict');
const {expand,mentions}=require('../static/named-scene.js');
const refs=[{id:'manual'},{id:'front'},{id:'side'}],voices=[{id:'other'},{id:'rex'}];
const foundation={title:'SampleHero',handle:'SampleHero2',category:'Character',description:'A robot with a black faceplate.',refIds:['front','side'],voiceId:'rex'};
const result=expand('@SampleHero2 walks. @samplehero2 says hello.',[foundation],refs,voices,true);
assert.deepEqual(result.errors,[]);
assert.match(result.prompt,/Preserve SampleHero's exact appearance as shown in <IMAGE_2> and <IMAGE_3> throughout the shot\./);
assert.match(result.prompt,/Voice for SampleHero: <AUDIO_1>\./);
assert(!result.prompt.includes('black faceplate'));
assert(!result.prompt.includes('@'));
assert(result.prompt.startsWith('Reference identities:'));
assert(result.prompt.endsWith('SampleHero walks. SampleHero says hello.'));
assert.equal((result.prompt.match(/<AUDIO_1>/g)||[]).length,1);
assert.match(expand('Say \"I am @SampleHero2.\"',[foundation],refs,voices,false).prompt,/Say \"I am SampleHero\./);
const reordered=expand('@SampleHero2',[foundation],[refs[2],refs[0],refs[1]],voices,false);
assert.match(reordered.prompt,/<IMAGE_2> and <IMAGE_0>/);
assert.equal(expand('@Unknown',[foundation],refs,voices,false).errors.length,1);
assert(expand('@SampleHero2',[foundation],[refs[0]],voices,false).errors.some(e=>e.includes('missing')));
assert(!expand('@SampleHero2',[foundation],refs,[],false).prompt.includes('<AUDIO_'));
assert(expand('@Voice',[{title:'Voice',handle:'Voice',category:'Character',refIds:[],voiceId:'rex'}],[],[],false).errors.length);
assert.deepEqual(mentions('user@example.com @SampleHero @SampleHero2'),['SampleHero','SampleHero2']);
assert(expand('@SampleHero',[foundation],refs,voices,false).errors.length);
const legacy=expand('@SampleHero2 walks.\n\nAsset cues:\n@SampleHero2: Wrong gold boots.\n\nReference context:\nCharacter: SampleHero (<IMAGE_7>). Long biography.',[foundation],refs,voices,false);
assert(!legacy.prompt.includes('Wrong gold boots')&&!legacy.prompt.includes('Long biography'));
assert.equal((legacy.prompt.match(/Preserve SampleHero/g)||[]).length,1);
assert.equal(expand(legacy.prompt,[foundation],refs,voices,false).prompt,legacy.prompt,'Recompilation must not duplicate context');
const voice=expand('@Narrator speaks.',[{title:'Narrator',handle:'Narrator',category:'Character',description:'Warm conversational delivery.',refIds:[],voiceId:'rex'}],[],voices,false);
assert(voice.prompt.includes('Warm conversational delivery.')&&!voice.prompt.includes('exact appearance'));
console.log('Named scene compiler: checks passed.');
