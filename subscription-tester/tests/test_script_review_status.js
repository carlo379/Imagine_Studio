const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {buildSync}=require('esbuild'),{JSDOM}=require('jsdom');
const compiled=path.resolve('.validation/script-review-status/status.cjs');
fs.mkdirSync(path.dirname(compiled),{recursive:true});
buildSync({entryPoints:['ui/script-review-status.tsx'],bundle:true,platform:'node',external:['react','react-dom'],outfile:compiled,logLevel:'silent'});
const dom=new JSDOM('<div id="root"></div>');
global.window=dom.window;global.document=dom.window.document;global.IS_REACT_ACT_ENVIRONMENT=true;
const React=require('react'),{act}=React,{createRoot}=require('react-dom/client'),{ScriptReviewStatus}=require(compiled);
const root=createRoot(document.getElementById('root'));let retries=0,drafts=0;
const render=(request,busy=false)=>act(()=>root.render(React.createElement(ScriptReviewStatus,{request,busy,retry:()=>retries++,draft:()=>drafts++})));
render({purpose:'production-details',status:'pending'});
assert.match(document.querySelector('[role=status]').textContent,/Completing production details/);
assert.equal(document.querySelectorAll('button').length,0);
render({purpose:'production-details',status:'error',error:'Example failure.'});
assert.match(document.querySelector('[role=alert]').textContent,/Example failure/);
assert.doesNotMatch(document.body.textContent,/No script saved yet/);
act(()=>document.querySelectorAll('button')[0].click());assert.equal(retries,1);
act(()=>document.querySelectorAll('button')[1].click());assert.equal(drafts,1);
render({purpose:'production-details',status:'error'},true);
assert.ok([...document.querySelectorAll('button')].every(b=>b.disabled));
render({purpose:'production-details',status:'done'});assert.equal(document.getElementById('root').textContent,'');
act(()=>root.unmount());
console.log('Script Review pending, failure, retry, disabled and success states passed.');
