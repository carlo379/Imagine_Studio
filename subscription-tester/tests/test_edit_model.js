const assert=require('node:assert/strict'),esbuild=require('esbuild');
const out=esbuild.buildSync({entryPoints:['ui/edit_model.ts'],bundle:true,write:false,platform:'node',format:'cjs'}).outputFiles[0].text;
const moduleObject={exports:{}};new Function('module','exports',out)(moduleObject,moduleObject.exports);
const {duration,offsets,normalizeClips,splitClip,moveClip}=moduleObject.exports;
const clip=(id,left=0,right=2,tr)=>({id,source:{kind:'take',id},in:left,out:right,label:id,volume:1,transition:tr});
const a=clip('a'),b=clip('b',0,2,{type:'dissolve',duration:.5}),c=clip('c');
const timeline={clips:[a,b,c],audio:[],titles:[],output:{fps:24}};
assert.equal(duration(timeline),5.5);assert.deepEqual(offsets(timeline.clips),[0,1.5,3.5]);
const split=splitClip(timeline,'b',2.5,()=> 'new');assert.deepEqual(split.map(c=>c.id),['a','b','new','c']);assert.equal(split[1].transition.duration,.5);assert.equal(split[2].transition.type,'cut');assert.equal(duration({...timeline,clips:split}),5.5);
assert.throws(()=>splitClip(timeline,'b',1.6,()=> 'bad'));assert.throws(()=>splitClip(timeline,'a',0,()=> 'bad'));
assert.deepEqual(moveClip([a,b,c],0,3).map(c=>c.id),['b','c','a']);
assert.equal(normalizeClips([b,a],24)[0].transition.type,'cut');assert.equal(normalizeClips([a,{...b,out:.5}],24)[1].transition.duration,.25);
const image={...a,source:{kind:'image',id:'picture'}};const images=splitClip({...timeline,clips:[image]},'a',1,()=> 'other');assert.deepEqual(images.map(c=>[c.in,c.out]),[[0,1],[0,1]]);assert.equal(duration({...timeline,clips:images}),2);
const uploaded=splitClip({...timeline,clips:[a]},'a',1,()=> 'other',true);assert.equal(uploaded[1].in,0);
assert.throws(()=>splitClip({...timeline,output:{fps:30}},'a',1/30,()=> 'too-short'));
console.log('Edit timing, overlapping transitions, safe split, still splits and reorder pass.');
